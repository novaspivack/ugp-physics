# An RS(5,k) codeword over GF(7) with evaluation points {x0,...,x4} ⊆ GF(7)
# is a vector (p(x0), p(x1), ..., p(x4)) for polynomial p of degree < k.
# Try evaluation points = {1,2,3,4,5} or {0,1,2,3,4} etc.

def poly_eval(coeffs, x, m):
    """Evaluate polynomial sum(coeffs[i]*x^i) mod m."""
    return sum(c * pow(x, i, m) % m for i, c in enumerate(coeffs)) % m

