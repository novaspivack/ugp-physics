orbit_names = {tuple(gen1): 'gen1', tuple(gen2): 'gen2',
               tuple(gen3): 'gen3', tuple(vacuum): 'vacuum'}

def name_of(v):
    t = tuple(v)
    return orbit_names.get(t, str(v))

def extended_gcd(a, b):
    if a == 0:
        return b, 0, 1
    g, x, y = extended_gcd(b % a, a)
    return g, y - (b // a) * x, x

def mod_inv(a, m):
    g, x, _ = extended_gcd(a % m, m)
    if g != 1:
        return None
    return x % m

