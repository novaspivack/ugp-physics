# ─────────────────────────────────────────────── Q(zeta_120) infrastructure
# zeta_120 = exp(2 pi i / 120).  The Galois group (Z/120)* has order phi(120) = 32.
# A basis for Q(zeta_120) over Q is {1, zeta_120, ..., zeta_120^{phi(120)-1}}
# filtered to coprime exponents mod 120.
# For a real number x to lie in Q(zeta_120), its minimal polynomial over Q must
# divide the 120th cyclotomic polynomial (degree phi(120) = 32) or one of its
# divisors.  We use the PSLQ-based integer-relation approach as a proxy.

CONDUCTOR = 120

def coprime_exponents(n: int) -> list[int]:
    """Exponents k in [1, n) with gcd(k, n) = 1."""
    from math import gcd
    return [k for k in range(1, n) if gcd(k, n) == 1]

def galois_basis_real(conductor: int, n_terms: int = 32) -> list[mp.mpf]:
    """Real parts of the Galois basis {cos(2 pi k / conductor)} for coprime k."""
    exps = coprime_exponents(conductor)
    # The real subfield of Q(zeta_n) is generated by cos(2 pi / n).
    # Basis: {cos(2 pi k / conductor) : k coprime to conductor, k <= conductor/2}
    seen: set[tuple[int, int]] = set()
    basis: list[mp.mpf] = [mp.mpf(1)]
    for k in exps:
        if 2 * k > conductor:
            continue
        basis.append(mp.cos(2 * mp.pi * k / conductor))
    return basis[:n_terms]

def pslq_membership(x: mp.mpf, basis: list[mp.mpf],
                    tol_coeff: int = 200) -> dict[str, Any]:
    """Test if x lies in the Q-span of basis using PSLQ.

    Returns dict with:
      found:      bool
      relation:   list of int (if found)
      residual:   float (reconstruction error)
    """
    # Use mpmath's identify function and PSLQ
    vec = [x] + list(basis)
    rel = mp.pslq(vec, tol=mp.mpf(f"1e-{mp.mp.dps // 2}"), maxcoeff=tol_coeff)
    if rel is None:
        return {"found": False, "relation": None, "residual": None}
    # Reconstruct: rel[0]*x + sum rel[i+1]*basis[i] = 0 iff x in span
    if rel[0] == 0:
        return {"found": False, "relation": list(rel), "residual": None}
    # x = - (1/rel[0]) * sum_{i>=1} rel[i]*basis[i-1]
    recon = -sum(mp.mpf(rel[i + 1]) * basis[i] for i in range(len(basis))) / mp.mpf(rel[0])
    residual = float(abs(recon - x))
    return {
        "found": True,
        "relation": [int(r) for r in rel],
        "residual": residual,
        "reconstructed": mp.nstr(recon, 10),
        "original":      mp.nstr(x, 10),
    }


